#!/usr/bin/env python3
"""satpi – receive_orchestrator

Single-pass workflow integrator. Looks up a pass by --pass-id in passes.json,
then chains receive_pass.py → post_processing.py. Called by the per-pass
systemd service generated by generate_refresh_units.py.

Per-step configuration (decode, db, plots, copy, notify) is read from
config.ini by post_processing.py itself — no extra flags needed here.

Author: Andreas Horvath
Project: satpi
"""

from __future__ import annotations

import argparse
import json
import logging
import os
import subprocess
import sys
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

sys.path.insert(0, str(Path(__file__).parent.parent / "lib"))
from read_config import read_config, ConfigError


logger = logging.getLogger("satpi.receive_orchestrator")


# --- Constants ---------------------------------------------------------------

RECEIVE_PASS_TIMEOUT = 180 * 60   # 3 h hard cap for the receive subprocess
POST_PROCESSING_TIMEOUT = 60 * 60  # 1 h hard cap for the post-processing chain


# --- Helpers -----------------------------------------------------------------

def setup_logger() -> None:
    """Log to stderr only. systemd captures it via the unit's journal,
    and the per-script logs (receive_pass.log, post_processing.log) inside
    the pass directory cover the per-pass forensics."""
    logger.setLevel(logging.INFO)
    logger.handlers.clear()

    fmt = logging.Formatter("%(asctime)s [%(levelname)s] %(message)s")
    ch = logging.StreamHandler()
    ch.setFormatter(fmt)
    logger.addHandler(ch)


def run_subprocess(
    cmd: List[str],
    *,
    timeout: int,
    description: str = "",
) -> Tuple[int, str, str]:
    """Run a subprocess, return (rc, stdout, stderr)."""
    desc = f": {description}" if description else ""
    logger.info("Running%s: %s", desc, " ".join(cmd))

    try:
        proc = subprocess.run(
            cmd,
            capture_output=True,
            text=True,
            timeout=timeout,
        )
        return proc.returncode, proc.stdout, proc.stderr
    except subprocess.TimeoutExpired:
        logger.error("Command timed out after %ds: %s", timeout, " ".join(cmd))
        return 124, "", f"Command timed out after {timeout}s"
    except Exception as e:
        logger.error("Command failed: %s", e)
        return 1, "", str(e)


def find_pass_in_json(
    pass_id: str,
    config: Dict[str, Any],
) -> Optional[Dict[str, Any]]:
    """Look up a pass by pass-id in passes.json. Returns the pass dict
    or None (with an error logged)."""
    base_dir = str(Path(__file__).resolve().parent.parent)
    pass_file = config.get("paths", {}).get("pass_file", "results/passes.json")
    pass_file = os.path.expanduser(pass_file)
    if not os.path.isabs(pass_file):
        pass_file = os.path.join(base_dir, pass_file)

    if not os.path.exists(pass_file):
        logger.error("Passes file not found: %s", pass_file)
        return None

    try:
        with open(pass_file, "r", encoding="utf-8") as f:
            data = json.load(f)
    except (json.JSONDecodeError, OSError) as e:
        logger.error("Failed to load passes file %s: %s", pass_file, e)
        return None

    for p in data.get("passes", []):
        if p.get("pass-id") == pass_id:
            return p

    logger.error("Pass-id '%s' not found in %s", pass_id, pass_file)
    return None


def receive_pass(
    config: Dict[str, Any],
    pass_data: Dict[str, Any],
    testmode: bool = False,
) -> Tuple[bool, Optional[str]]:
    """Run receive_pass.py for the given pass-id.

    Returns: (success, pass_output_dir)
    """
    base_dir = str(Path(__file__).resolve().parent.parent)
    script = os.path.join(base_dir, "bin", "receive_pass.py")

    if not os.path.exists(script):
        logger.error("receive_pass.py not found: %s", script)
        return False, None

    python_bin = config.get("paths", {}).get("python_bin", "python3")
    pass_id = pass_data.get("pass-id", "")

    if not pass_id:
        logger.error("Pass data missing pass-id")
        return False, None

    cmd = [python_bin, script, "--pass-id", pass_id]
    if testmode:
        cmd.append("--testmode")
        logger.info("Running in test mode")

    rc, _stdout, stderr = run_subprocess(
        cmd,
        timeout=RECEIVE_PASS_TIMEOUT,
        description=f"receive_pass for {pass_data.get('satellite', 'UNKNOWN')}",
    )

    if rc != 0:
        logger.error("receive_pass failed (rc=%s)", rc)
        if stderr.strip():
            logger.error("stderr: %s", stderr.strip())
        return False, None

    # Resolve pass_output_dir for post_processing.
    output_dir = config.get("paths", {}).get("output_dir", "")
    if output_dir:
        output_dir = os.path.expanduser(output_dir)
        pass_output_dir = os.path.join(output_dir, pass_id)
        if os.path.isdir(pass_output_dir):
            logger.info("Pass output directory: %s", pass_output_dir)
            return True, pass_output_dir
        logger.warning("Pass output directory does not exist: %s", pass_output_dir)

    logger.warning("Could not determine pass_output_dir")
    return True, None


def post_process_pass(
    config: Dict[str, Any],
    pass_output_dir: str,
) -> bool:
    """Run post_processing.py for the given pass output directory."""
    base_dir = str(Path(__file__).resolve().parent.parent)
    script = os.path.join(base_dir, "bin", "post_processing.py")

    if not os.path.exists(script):
        logger.warning("post_processing.py not found: %s", script)
        return False

    python_bin = config.get("paths", {}).get("python_bin", "python3")

    cmd = [python_bin, script, "--pass-output-dir", pass_output_dir]

    rc, _stdout, stderr = run_subprocess(
        cmd,
        timeout=POST_PROCESSING_TIMEOUT,
        description=f"post_processing for {os.path.basename(pass_output_dir)}",
    )

    if rc != 0:
        logger.error("post_processing failed (rc=%s)", rc)
        if stderr.strip():
            logger.error("stderr: %s", stderr.strip())
        return False

    return True


# --- CLI & Main --------------------------------------------------------------

def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(
        description="Run the receive + post-processing chain for a single pass.",
        epilog="""
Per-pass systemd usage (from generate_refresh_units.py):
    ExecStart=/usr/bin/python3 .../receive_orchestrator.py --pass-id <ID>

Manual usage:
    # Run the chain for a real upcoming pass NOW:
    python3 receive_orchestrator.py --pass-id 2026-05-19_20-33-59_METEOR-M2-3

    # End-to-end smoke test (uses [testing] duration_seconds, typ. 60s):
    python3 receive_orchestrator.py --pass-id <ID> --testmode
        """,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )

    p.add_argument(
        "--pass-id",
        required=True,
        metavar="ID",
        help="Pass identifier (looked up in passes.json). "
             "Format: YYYY-MM-DD_HH-MM-SS_SATELLITE",
    )
    p.add_argument(
        "--testmode",
        action="store_true",
        help="Use [testing] duration_seconds instead of actual pass duration. "
             "Makes the full chain runnable in ~1 min for smoke tests.",
    )

    return p.parse_args()


def main() -> int:
    args = parse_args()

    base_dir = str(Path(__file__).resolve().parent.parent)
    config_path = os.path.join(base_dir, "config", "config.ini")

    try:
        config = read_config(config_path)
    except ConfigError as e:
        print(f"[receive_orchestrator] CONFIG ERROR: {e}", file=sys.stderr)
        return 2

    setup_logger()
    logger.info(
        "receive_orchestrator: pass-id=%s testmode=%s",
        args.pass_id, args.testmode,
    )

    # Look up pass-id in passes.json
    pass_data = find_pass_in_json(args.pass_id, config)
    if not pass_data:
        return 1

    # Step 1: receive
    logger.info("Step 1: Receiving satellite pass")
    recv_ok, pass_output_dir = receive_pass(config, pass_data, testmode=args.testmode)
    if not recv_ok:
        logger.error("Pass reception failed")
        return 1
    logger.info("Pass reception completed successfully")

    # Step 2: post-processing — failure here is NOT fatal. The CADU is on
    # disk and the pass can be reprocessed manually via:
    #   python3 bin/post_processing.py --pass-id <ID> --decode --db --plots
    if pass_output_dir:
        logger.info("Step 2: Post-processing pass")
        if post_process_pass(config, pass_output_dir):
            logger.info("Post-processing completed successfully")
        else:
            logger.warning(
                "Post-processing failed but reception succeeded — "
                "manual recovery: post_processing.py --pass-id %s",
                args.pass_id,
            )
    else:
        logger.warning("No output directory, skipping post-processing")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
